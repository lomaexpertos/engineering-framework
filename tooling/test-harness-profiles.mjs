import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { buildSkillAdapters } from './harness-profiles.mjs';

const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'harness-profiles-'));
const source = path.join(temporary, 'source');
const consumer = path.join(temporary, 'consumer');
const put = (root, file, content) => { fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true }); fs.writeFileSync(path.join(root, file), content); };
const skill = name => `---\nname: ${name}\ndescription: Use ${name} when its domain changes.\n---\n\n# ${name}\n`;
const config = value => put(consumer, '.harness/project/config.json', JSON.stringify(value));
try {
  fs.mkdirSync(consumer);
  for (const name of ['coordinate-work','database-schema-change','implement-ui-change','infra-change','security-review']) put(source, `skills/${name}/SKILL.md`, skill(name));
  let result = buildSkillAdapters(source, consumer);
  assert.equal(result.skills.length, 5);
  assert.equal(result.profiles, null);
  config({ schema_version: 1, profiles: ['frontend'] });
  result = buildSkillAdapters(source, consumer);
  assert.deepEqual(result.skills, ['coordinate-work','implement-ui-change']);
  assert.deepEqual(result.profiles, ['core','frontend']);
  config({ schema_version: 1, profiles: [] });
  assert.deepEqual(buildSkillAdapters(source, consumer).skills, ['coordinate-work']);
  config({ schema_version: 1, profiles: ['unknown'] });
  assert.throws(() => buildSkillAdapters(source, consumer), /Unknown/);
  config({ schema_version: 1, profiles: ['core','core'] });
  assert.throws(() => buildSkillAdapters(source, consumer), /duplicate/);
  config({ schema_version: 1, profiles: ['core','database','security'] });
  result = buildSkillAdapters(source, consumer);
  assert.deepEqual(result.skills, ['coordinate-work','database-schema-change','security-review']);
  put(consumer, '.harness/project/skills/guide/SKILL.md', skill('guide'));
  put(consumer, '.harness/project/skills/README.md', '# Local skill router\n');
  put(consumer, '.harness/project/skills/guide/references/details.md', '# Local details\n');
  result = buildSkillAdapters(source, consumer);
  assert.deepEqual(result.localSkills, ['project-guide']);
  assert.match(result.files.get('.agents/skills/project-guide/SKILL.md').content.toString(), /^name: project-guide$/m);
  assert.ok(result.files.get('.claude/skills/project-guide/references/details.md').content.equals(result.files.get('.agents/skills/project-guide/references/details.md').content));
  assert.match(fs.readFileSync(path.join(consumer,'.harness/project/skills/guide/SKILL.md'),'utf8'), /^name: guide$/m);
  put(source, 'skills/project-guide/SKILL.md', skill('project-guide'));
  assert.throws(() => buildSkillAdapters(source, consumer), /collides/);
  fs.rmSync(path.join(source,'skills/project-guide'), { recursive: true });
  fs.symlinkSync('/tmp',path.join(consumer,'.harness/project/skills/guide/escape'));
  assert.throws(() => buildSkillAdapters(source, consumer), /symlink/);
  fs.unlinkSync(path.join(consumer,'.harness/project/skills/guide/escape'));
  put(consumer, '.harness/project/skills/guide/SKILL.md', skill('other'));
  assert.throws(() => buildSkillAdapters(source, consumer), /metadata/);
  put(consumer, '.harness/project/skills/guide/SKILL.md', skill('guide').replace('Use guide when its domain changes.', 'Long discovery '.repeat(1000)));
  assert.throws(() => buildSkillAdapters(source, consumer), /budget/);
  console.log('Harness profile selection and local skill adapter tests passed.');
} finally { fs.rmSync(temporary, { recursive: true, force: true }); }
